-- Проверка по PreviousDate такое не поймает: дыр между загруженными датами нет,
-- новые даты просто перестали появляться.
-- Нормальный разрыв между публикациями — до 3 дней (суббота -> вторник), поэтому порог 4.
-- В новогодние каникулы проверка сработает — это ожидаемо, ЦБ не публикует курсы ~10 дней.
-- COALESCE: пустая таблица — тоже ошибка, а не «проверка пройдена».

SELECT
    MAX(rate_date)                  AS last_date,
    CURRENT_DATE - MAX(rate_date)   AS days_old
FROM rates
HAVING COALESCE(CURRENT_DATE - MAX(rate_date), 9999) > 4; --- для теста убрал 9999 
