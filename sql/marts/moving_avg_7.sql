-- Скользящее среднее по последним 7 публикациям каждой валюты
-- ROWS считает строки, а не дни: 7 публикаций +- полторы календарные недели, потому что в выходные курс не публикуется
-- points показывает сколько точек реально попало в окно: у первых шести дат истории их меньше семи и среднее там неполное

SELECT
    char_code,
    rate_date,
    value_per_1,
    ROUND(AVG(value_per_1) OVER w7, 4) AS ma7,
    COUNT(*) OVER w7                   AS points
FROM rates
WINDOW w7 AS (
    PARTITION BY char_code
    ORDER BY rate_date
    ROWS BETWEEN 6 PRECEDING AND CURRENT ROW
)
ORDER BY char_code, rate_date;
